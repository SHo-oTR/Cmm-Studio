use std::fmt::Write;
use chrono::Local;
use crate::cad::b_rep_features::{FeatureMeasurementPlan, FeatureType};

pub struct DmisWriter;

impl DmisWriter {
    /// Bir veya birden fazla ölçüm planını ISO 22093 uyumlu DMIS programına dönüştürür
    pub fn generate_dmis(plans: &[FeatureMeasurementPlan]) -> String {
        let mut dmis = String::new();
        let now = Local::now().format("%Y-%m-%d %H:%M:%S").to_string();

        // 1. DMIS BAŞLIK VE ORTAM TANIMI
        writeln!(&mut dmis, "$$ DMIS generated by CMM Studio").unwrap();
        writeln!(&mut dmis, "$$ Date: {}", now).unwrap();
        writeln!(&mut dmis, "DMISMN/'CMM_STUDIO_PROGRAM', 05.2").unwrap();
        writeln!(&mut dmis, "UNITS/MM, ANGDEC").unwrap();
        writeln!(&mut dmis, "DECPL/ALL, 4").unwrap();
        writeln!(&mut dmis, "MODE/AUTO, PROG, MAN").unwrap();
        writeln!(&mut dmis, "PRCOMP/ON").unwrap();
        writeln!(&mut dmis, "SNSET/APPRCH, 5.0000").unwrap();
        writeln!(&mut dmis, "SNSET/RETRCT, 3.0000").unwrap();
        writeln!(&mut dmis, "$$").unwrap();

        // 2. ÖLÇÜM UNSURLARI VE TEMAS NOKTALARI
        for (idx, plan) in plans.iter().enumerate() {
            let feat_name = format!("F_{}_{}", plan.feature.label, idx + 1);

            // Emniyet düzlemine çıkış
            writeln!(
                &mut dmis,
                "RAPTO/CART, {:.4}, {:.4}, {:.4}",
                plan.feature.nominal_center.x,
                plan.feature.nominal_center.y,
                plan.safety_clearance_z
            ).unwrap();

            match plan.feature.feature_type {
                FeatureType::CylinderHole => {
                    let dia = plan.feature.diameter.unwrap_or(0.0);
                    let c = plan.feature.nominal_center;
                    let v = plan.feature.nominal_vector;

                    // Unsur Tanımı (Nominal Feature Definition)
                    writeln!(
                        &mut dmis,
                        "F({}) = FEAT/CIRCLE, INNER, CART, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}",
                        feat_name, c.x, c.y, c.z, v.x, v.y, v.z, dia
                    ).unwrap();

                    // Ölçüm Komutu
                    writeln!(&mut dmis, "MEAS/CIRCLE, F({}), {}", feat_name, plan.points.len()).unwrap();
                    for pt in &plan.points {
                        writeln!(
                            &mut dmis,
                            "PTMEAS/CART, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}",
                            pt.target.x, pt.target.y, pt.target.z, pt.normal.x, pt.normal.y, pt.normal.z
                        ).unwrap();
                    }
                    writeln!(&mut dmis, "ENDMES").unwrap();
                }
                FeatureType::Plane => {
                    let c = plan.feature.nominal_center;
                    let v = plan.feature.nominal_vector;

                    writeln!(
                        &mut dmis,
                        "F({}) = FEAT/PLANE, CART, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}",
                        feat_name, c.x, c.y, c.z, v.x, v.y, v.z
                    ).unwrap();

                    writeln!(&mut dmis, "MEAS/PLANE, F({}), {}", feat_name, plan.points.len()).unwrap();
                    for pt in &plan.points {
                        writeln!(
                            &mut dmis,
                            "PTMEAS/CART, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}, {:.4}",
                            pt.target.x, pt.target.y, pt.target.z, pt.normal.x, pt.normal.y, pt.normal.z
                        ).unwrap();
                    }
                    writeln!(&mut dmis, "ENDMES").unwrap();
                }
                _ => {}
            }
            writeln!(&mut dmis, "$$").unwrap();
        }

        writeln!(&mut dmis, "ENDFIL").unwrap();
        dmis
    }
}
